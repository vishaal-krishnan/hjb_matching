def grad_w_fn(model, x, t):

    x = x.detach().requires_grad_(True)
    t = t.detach()

    output = model(x, t)  # shape (B,)
    grad_w = torch.autograd.grad(
        outputs=output.sum(), inputs=x,
        create_graph=True, retain_graph=True, only_inputs=True
    )[0]

    return grad_w

def Euler_Maruyama_sampler_ou(score_model, theta, D, batch_size, num_steps, device='cuda'):
    # Time steps: from s=1 → s=eps (reverse)
    # time_steps = torch.linspace(1., eps, num_steps, device=device)
    time_steps = torch.linspace(1.0, 0.0, steps=num_steps + 2, device=device)[1:-1]
    step_size = time_steps[0] - time_steps[1]

    # Initialize from N(0, D / theta)
    stationary_std = (D / theta) ** 0.5
    x = torch.randn(batch_size, 1, 28, 28, device=device) * stationary_std
    init_x = x.clone()

    score_model.eval()
    for s in time_steps:
        batch_t = torch.ones(batch_size, device=device) * s
        grad_w = grad_w_fn(score_model, x, batch_t)  # ∇W(x,s)

        drift = theta * x + grad_w  # OU drift + learned correction
        noise = torch.randn_like(x) * (2 * D * step_size) ** 0.5

        x = x + step_size * drift + noise

        # convert to original range

    return x, init_x

def OU_forward_validate(model, x0, T=1.0, dt=0.01):

    with torch.no_grad():
        num_steps = int(T / dt)
        x = x0.clone()

        w_0 = model(x, torch.zeros(x.shape[0])).detach().cpu()
        traj_w = [w_0]

        for step in range(num_steps):
            noise = torch.randn_like(x)
            drift = -theta * x * dt
            diffusion = torch.sqrt(torch.tensor(2 * D * dt, device=x.device)) * noise
            x = x + drift + diffusion

            t_batched = torch.ones(x.shape[0], device=device) * step * dt
            w = model(x, t_batched).detach().cpu()

            traj_w.append(w)

        #
        traj_w = torch.stack(traj_w, dim=1)
        traj_w = traj_w.view(traj_w.shape[0], traj_w.shape[1], -1)

    return traj_w  # return final state and full trajectory

def show_bump(model, x0, T=1.0, dt=0.01):
    model.eval()
    num_steps = int(T / dt)
    times = torch.linspace(0, T, num_steps + 1, device=x0.device)
    x = x0.clone()
    traj = [x0.clone()]

    # rollout traj
    for _ in range(num_steps):
        noise = torch.randn_like(x)
        drift = -theta * x * dt
        diffusion = torch.sqrt(torch.tensor(2 * D * dt, device=x.device)) * noise
        x = x + drift + diffusion
        traj.append(x.clone())

    traj = torch.stack(traj)  # [T+1, B, ...]
    B = traj.shape[1]

def create_video(score_model, theta, D, batch_size, num_steps, device='cuda'):
    time_steps = torch.linspace(1.0, 0.0, steps=num_steps + 2, device=device)[1:-1]
    step_size = time_steps[0] - time_steps[1]

    # Initialize from N(0, D / theta)
    stationary_std = (D / theta) ** 0.5
    x = torch.randn(batch_size, 1, 28, 28, device=device) * stationary_std
    frames = []  # Store frames for the video

    for i, s in enumerate(time_steps):
        batch_t = torch.ones(batch_size, device=device) * s
        grad_w = grad_w_fn(score_model, x, batch_t)  # ∇W(x,s)

        drift = theta * x + grad_w  # OU drift + learned correction
        noise = torch.randn_like(x) * (2 * D * step_size) ** 0.5

        x = x + step_size * drift + noise

        # conver to orignal range
        samples = x
        samples = samples.clamp(-1.0, 1.0)
        samples = (samples + 1.0)/2

        # Save current frame
        if i%10 == 0:
          grid = make_grid(samples, nrow=int(np.sqrt(batch_size)))
          img = grid.permute(1, 2, 0).cpu().numpy()
          frames.append(img)

    # Plot animation
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.axis('off')
    im = ax.imshow(frames[0], vmin=0., vmax=1.)

    def update(i):
        im.set_data(frames[i])
        return [im]

    ani = animation.FuncAnimation(fig, update, frames=len(frames), interval=50, blit=True)
    plt.close(fig)  # Prevent static image display
    return ani


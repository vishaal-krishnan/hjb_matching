# --- OU sampling ---
def OU_sample(x, t):
    device = x.device
    t_batched = torch.ones(x.shape[0], device=device) * t
    exp_term = torch.exp(-theta * t_batched).view(-1, 1, 1, 1)
    mean = exp_term * x
    var = (D / theta) * (1. - exp_term**2)
    std = torch.sqrt(var).view(-1, 1, 1, 1)

    # Sample from OU conditional
    noise = torch.randn_like(x)
    x_t = mean + std * noise  # OU sample
    return x_t


def spatial_smoothness(w, kernel_size=3):
    pad = kernel_size // 2
    grad_x = w[:, :, :, 1:] - w[:, :, :, :-1]
    grad_y = w[:, :, 1:, :] - w[:, :, :-1, :]
    return (grad_x**2).mean() + (grad_y**2).mean()


# --- loss fk ---
def loss_fn_single_time(model, x, t, beta, theta, D, eps=1e-5):

    batch_size = x.shape[0]
    device = x.device

    # Sample random times t ~ Uniform(eps, 1)
    random_t = torch.rand(batch_size, device=device) * (1. - eps) + eps
    random_t_neg = torch.rand(batch_size, device=device) * (1. - eps) + eps

    # Compute OU mean and std
    exp_term = torch.exp(-theta * random_t).view(-1, 1, 1, 1)
    mean = exp_term * x
    var = (D / theta) * (1. - exp_term**2)
    std = torch.sqrt(var).view(-1, 1, 1, 1)

    # Sample from OU conditional
    noise = torch.randn_like(x)
    x_t = mean + std * noise  # OU sample

    # Evaluate model outputs
    w = model(x_t, random_t)
    z = torch.exp(beta * w)

    w0 = model(x, torch.zeros_like(random_t))
    z0 = torch.exp(beta * w0)

    # w1 = model(torch.sqrt(D / theta).view(-1, 1, 1, 1) * noise, torch.ones_like(random_t))
    # z1 = torch.exp(beta * w1)

    # Feynman-Kac loss (target from x0 at t=0)
    target = torch.exp(- beta * random_t) * z0
    loss_fk = (z - target) ** 2

    # Optional dual loss
    loss_dual = (z0 - 1.0)**2

    # Negative sampling
    w_neg = model(x_t, random_t_neg)
    z_neg = torch.exp(beta * w_neg)
    loss_neg = (z_neg - 0.1)**2

    # Spatial loss
    spatial_loss = spatial_smoothness(x_t)  # w_img_batch has shape (B, 1, H, W)

    total_loss = 1e0 * loss_fk + 1e0 * loss_dual + 1e-3 * spatial_loss + 1e-1 * loss_neg
    return total_loss.mean(), loss_fk.mean(), loss_dual.mean()




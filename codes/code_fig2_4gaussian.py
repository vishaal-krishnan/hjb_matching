def forward_loss_fn(w_params, pos0, key, target_pos, steps, T_tot, guidance_strength, step_mode, train_mode):
    subkey1, subkey2 = jax.random.split(key)

    # rollout the trajectory
    step_idx_vec, dt_vec, traj, traj_w, traj_nu = rollout(pos0, subkey1, w_params, None, guidance_strength, steps, T_tot, step_mode, train_mode)

    final_pos = traj[-1]
    w_0 = traj_w[0]
    w_T = traj_w[-1]

    # dual loss
    # loss1 = jnp.mean(w_0) - jnp.mean(w_T) # default
    loss1 = 1e-1 * (jnp.mean(w_T) - jnp.mean(w_0)) + jnp.mean((w_0-10.0)**2)
    # loss1 = - jnp.mean(w_0) + (jnp.mean(w_T) + 1.0) ** 2.0

    # FK losses
    loss2 = loss_fk(w_params, None, traj, step_idx_vec, dt_vec, beta)
    loss3 = loss_fk_local(w_params, None, traj, step_idx_vec, dt_vec, beta)

    # negative sampling
    pos_ns = jax.random.uniform(subkey2, shape=traj.shape, minval=-5.0, maxval=5.0).reshape(-1, 2)

    # regularize w
    step_ns = jnp.arange(steps)[:,None].repeat(traj.shape[1], axis=1).reshape(-1)
    w_ns = w_net.apply(w_params, pos_ns, step_ns)
    penalty1 = jnp.mean(w_ns ** 2)

    # weights regularization
    # l2 = sum([jnp.sum(jnp.square(p)) for p in jax.tree_util.tree_leaves(w_params)])

    # total loss
    # loss = 1e-2 * loss1 + loss2 + loss3 + 0.1 * penalty1 # default
    loss = 1e-2 * loss1 + loss2 + 0.1 * penalty1

    return loss.squeeze(), (loss1.squeeze(), loss2.squeeze(), loss3.squeeze(), final_pos, traj)


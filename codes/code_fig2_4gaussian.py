@jax.jit
def loss_fk(w_params, nu_params, trajectory, step_idx_vec, dt_vec, beta):

    steps, batch_size, _ = trajectory.shape

    # --- Prepare time-space points ---
    x_k = trajectory[:-1]  # (steps-1, batch, 2)
    x_kp1 = trajectory[1:]  # (steps-1, batch, 2)
    dx = x_kp1 - x_k # (steps-1, batch, 2)
    s_k = step_idx_vec[:-1][:, None].repeat(batch_size, axis=1)  # (steps-1, batch)
    dt_k = dt_vec[:-1][:, None].repeat(batch_size, axis=1)  # (steps-1, batch)

    # xk_s = jnp.concatenate([x_k, s_k[..., None]], axis=-1)  # (steps-1, batch, 3)
    # xk_s_flat = xk_s.reshape(-1, 3)
    xk_flat = x_k.reshape(-1, 2)
    s_k_flat = s_k.reshape(-1)
    dt_k_flat = dt_k.reshape(-1)

    # Terminal points
    x_1 = trajectory[-1]  # (batch, 2)
    # s_1 = jnp.full((batch_size, 1), s_values[-1])
    # x1_s = jnp.concatenate([x_1, s_1], axis=-1)

    # --- Evaluate Z ---
    W_k = w_net.apply(w_params, xk_flat, s_k_flat)
    Z_k = jnp.exp(beta * W_k).squeeze()  # (steps-1) * batch

    #
    # W_1 = w_net.apply(w_params, x_1)
    # Z_1 = jnp.exp(beta * W_1).squeeze()       # batch
    # Z_1_repeated = jnp.tile(Z_1, reps=(steps - 1,)) # Broadcast Z_1 to match Z_k

    #
    x_0 = trajectory[0]
    # x_0_repeated = jnp.tile(x_0, reps=(steps - 1,)) # Broadcast x_0 to match x_k
    x_0_repeated = jnp.repeat(x_0, steps - 1, axis=0)
    x_0_repeated_flat = x_0_repeated.reshape(-1, 2)
    # W_0_repeated = w_net.apply(w_params, x_0_repeated_flat, s_k_flat)
    W_0_repeated = w_net.apply(w_params, x_0_repeated_flat, jnp.zeros_like(s_k_flat))
    Z_0_repeated = jnp.exp(beta * W_0_repeated).squeeze()       # batch
    # Z_0_repeated = jnp.tile(Z_0, reps=(steps - 1,)) # Broadcast Z_0 to match Z_k

    # print(x_0_repeated_flat.shape)
    # print(s_k_flat.shape)
    # print(W_0_repeated.shape)

    # --- Evaluate nu ---
    if nu_params is None:
        nu_k = jnp.ones((xk_flat.shape[0],))
    else:
        nu_k = nu_net.apply(nu_params, xk_flat).squeeze()

    # --- Compute path costs ---
    # s_k_flat = s_k.reshape(-1)
    # cost = nu_k * (1.0 - s_k_flat)  # General nu
    cost_single = nu_k * dt_k_flat
    cost_single = cost_single.reshape(steps-1, batch_size)
    cost = - beta * jnp.cumsum(cost_single, axis = 0)
    cost_flat = cost.reshape(-1)

    # penalty
    x_mid = 0.5 * (x_k + x_kp1)
    p1_single = guidance_strength * (x_mid * dx).sum(axis=-1)
    p1 = (1.0/2.0 * D) * jnp.cumsum(p1_single, axis = 0)
    p1_flat = p1.reshape(-1)

    p2_single = guidance_strength ** 2 * (x_mid ** 2 * dt_k[...,None]).sum(axis=-1)
    p2 = - (1.0/4.0 * D) * jnp.cumsum(p2_single, axis = 0)
    p2_flat = p2.reshape(-1)

    # --- FK target ---
    # target = jnp.exp(beta * cost) * Z_1_repeated
    # target = jnp.exp(cost_flat + p1_flat + p2_flat) * Z_0_repeated
    target = jnp.exp(cost_flat) * Z_0_repeated

    # --- Squared loss ---
    loss_per_point = (Z_k - target) ** 2
    fk_loss = jnp.mean(loss_per_point)

    return fk_loss


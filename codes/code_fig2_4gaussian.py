def init_sample(k, N, means=[(2.0, 0.0), (0.0, 2.0), (0.0, -2.0), (-2.0, 0.0)], std=0.2):
    keys = jax.random.split(k, 4)
    N_per_cluster = N // 4
    clusters = []
    for i in range(4):
        samples = jax.random.normal(keys[i], (N_per_cluster, 2)) * std + jnp.array(means[i])
        clusters.append(samples)
    return jnp.concatenate(clusters, axis=0)



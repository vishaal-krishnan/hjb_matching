def compute_grad(params, x, idx, mlp):
    # x: (N, 2)

    def single_forward(x_single, idx_single):
        x_single = x_single[None, :]               # (1,2)
        w_single = mlp.apply(params, x_single, idx_single) # idx_single should be (1,)
        return w_single.squeeze()                # scalar

    # grad_fn = jax.vmap(jax.grad(single_forward), in_axes=0)
    # idx_expanded = jnp.full((x.shape[0],), idx)
    # grads = grad_fn(x, idx_expanded)  # x is (N, 2)

    grad_fn = jax.vmap(jax.grad(single_forward), in_axes=(0, None))
    grads = grad_fn(x, idx)  # x is (N, 2)
    return grads


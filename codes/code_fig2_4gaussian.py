@jax.jit
def loss_fk_local(w_params, nu_params, trajectory, step_idx_vec, dt_vec, beta):

    steps, batch_size, _ = trajectory.shape

    # Get pairs (x_k, s_k) and (x_{k+1}, s_{k+1})
    x_k = trajectory[:-1]            # shape (steps - 1, batch, 2)
    x_kp1 = trajectory[1:]          # shape (steps - 1, batch, 2)

    s_k = step_idx_vec[:-1][:, None].repeat(batch_size, axis=1)  # (steps-1, batch)
    s_kp1 = step_idx_vec[1:][:, None].repeat(batch_size, axis=1)
    dt_k = dt_vec[:-1][:, None].repeat(batch_size, axis=1)
    dt_kp1 = dt_vec[1:][:, None].repeat(batch_size, axis=1)

    # Stack spatial and time dimensions
    # xk_s = jnp.concatenate([x_k, s_k[..., None]], axis=-1)       # (steps-1, batch, 3)
    # xkp1_s = jnp.concatenate([x_kp1, s_kp1[..., None]], axis=-1) # (steps-1, batch, 3)

    # Flatten for batch evaluation
    # xk_s_flat = xk_s.reshape(-1, 3)
    # xkp1_s_flat = xkp1_s.reshape(-1, 3)
    xk_flat = x_k.reshape(-1, 2)
    xkp1_flat = x_kp1.reshape(-1, 2)
    s_k_flat = s_k.reshape(-1)
    s_kp1_flat = s_kp1.reshape(-1)
    dt_k_flat = dt_k.reshape(-1)
    dt_kp1_flat = dt_kp1.reshape(-1)

    # Evaluate Z and nu
    W_k = w_net.apply(w_params, xk_flat, s_k_flat)
    Z_k = jnp.exp(beta * W_k).squeeze()
    W_kp1 = w_net.apply(w_params, xkp1_flat, s_kp1_flat)
    Z_kp1 = jnp.exp(beta * W_kp1).squeeze()


    if nu_params is None:
        nu_k = jnp.ones((xk_flat.shape[0],))
    else:
        nu_k = nu_net.apply(nu_params, xk_flat).squeeze()

    #
    cost = beta * nu_k * dt_k_flat

    dx = x_kp1 - x_k
    x_mid = 0.5 * (x_k + x_kp1)
    dt_mid = 0.5 * (dt_k + dt_kp1)
    p1_single = - (1.0/2.0 * D) * guidance_strength * (x_mid * dx).sum(axis=-1)
    p1_single_flat = p1_single.reshape(-1)

    p2_single = (1.0/4.0 * D) * guidance_strength ** 2 * (x_mid ** 2 * dt_mid[...,None]).sum(axis=-1)
    p2_single_flat = p2_single.reshape(-1)

    # Compute FK local loss vectorized
    target = jnp.exp(cost + p1_single_flat + p2_single_flat) * Z_kp1

    # Squared error
    loss_per_point = (Z_k - target) ** 2

    # Average over all (steps - 1) * batch samples
    fk_local_loss = jnp.mean(loss_per_point)

    return fk_local_loss


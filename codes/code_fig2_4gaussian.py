"""### rollout"""

# --- Single Rollout ---
@partial(jax.jit, static_argnums=(4,5,6,7,8,9,10))
def rollout(pos0, key, w_params, nu_params, guidance_strength, steps, T_tot, step_mode, train_mode, target_pos=jnp.zeros((1,2)), steps_beyond_horizon = 0):
    def body(state, inputs):
        step_idx, dt = inputs
        pos, key = state
        new_pos, new_key, w, nu = step(pos, target_pos, guidance_strength, key, w_params, nu_params, step_idx, dt, step_mode, train_mode)
        return (new_pos, new_key), (new_pos, w, nu)

    init_state = (pos0, key)
    step_idx_vec = jnp.arange(steps)
    # weights = (step_idx_vec + 1) ** 0.5
    weights = jnp.ones_like(step_idx_vec)
    dt_vec = weights / jnp.sum(weights) * T_tot

    if step_mode == "focusing":
        pass

    elif step_mode == "reversing":
        step_idx_vec = jnp.flip(step_idx_vec[:-1])
        dt_vec = jnp.flip(dt_vec[:-1])
        # generative step beyond horizon
        if steps_beyond_horizon > 0:
            last_step = step_idx_vec[-1]
            last_dt = dt_vec[-1]
            step_idx_vec = jnp.concatenate([step_idx_vec, jnp.repeat(last_step, steps_beyond_horizon)])
            dt_vec = jnp.concatenate([dt_vec, jnp.repeat(last_dt, steps_beyond_horizon)])

    else:
        raise ValueError("Invalid step_mode")

    scan_inputs = (step_idx_vec, dt_vec)
    (_, _), (traj, traj_w, traj_nu) = jax.lax.scan(body, init_state, scan_inputs)

    return step_idx_vec, dt_vec, traj, traj_w, traj_nu

"""### train step"""

@partial(jax.jit, static_argnums=(2,3,7))
def train_step(w_params, w_opt_state, steps, T_tot, pos0, key, target_pos, guidance_strength):
    (loss, (loss1, loss2, loss3, final_pos, traj)), grads = jax.value_and_grad(forward_loss_fn, has_aux=True)(
        w_params, pos0, key, target_pos, steps, T_tot, guidance_strength, step_mode="focusing", train_mode="pretraining")


def w_net_fn(hidden_dim=64, num_layers=8, num_steps=100):
    # PE
    class PosEmbed(hk.Module):
        def __init__(self, num_steps, dim, name=None):
            super().__init__(name=name)
            self.num_steps = num_steps
            self.dim = dim

        def __call__(self, positions):  # positions: (N,)
            embed_table = hk.get_parameter("pos_embed", [self.num_steps, self.dim],
                                           init=hk.initializers.TruncatedNormal(stddev=0.02))
            return embed_table[positions]  # (N, dim)

    # network
    def net_fn(x,step_expanded):

        x_embed = hk.nets.MLP([hidden_dim, hidden_dim])(x)
        step_embed = PosEmbed(num_steps=num_steps, dim=hidden_dim)(step_expanded)
        h = x_embed + step_embed

        for _ in range(num_layers):
            shortcut = h
            h = hk.Linear(hidden_dim)(h)
            h = jax.nn.gelu(h)
            h = hk.Linear(hidden_dim)(h)
            # h = hk.LayerNorm(axis=-1, create_scale=True, create_offset=True)(h)

            if shortcut.shape[-1] != hidden_dim:
                shortcut = hk.Linear(hidden_dim)(shortcut)
            h = h + shortcut

        # output layer
        h = hk.Linear(1)(h)
        return h

    return net_fn


# --- nu network ---
def nu_net_fn(hidden_dim=128, num_layers=10):
    def nu_net(x):
        h = x
        for _ in range(num_layers):
            h = hk.Linear(hidden_dim)(h)
            h = jax.nn.gelu(h)
        h = hk.Linear(1)(h)  # Output a scalar
        nu = 1.0 + 0.5 * jax.nn.tanh(h)
        return nu

    return nu_net


